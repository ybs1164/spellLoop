const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = vm.createContext({ console, assert, TD: new Proxy({}, { get: () => 0 }) });
for (const path of ['js/util.js', 'js/input.js', 'js/cards.js', 'js/entities.js', 'js/stages.js', 'js/icons.js', 'js/ui.js', 'js/game.js']) {
  vm.runInContext(fs.readFileSync(path, 'utf8'), context, { filename: path });
}
vm.runInContext(`
  UI.hideOverlay = UI.showHud = () => {};
  UI.open = function(html, mode) { this.html = html; this.mode = mode; };
  UI.overlay = { querySelector: () => null };
  const game = Object.create(Game.prototype);
  game.events = new EventBus(); game.hash = createSpatialIndex(); game._near = [];
  game.w = 1000; game.h = 800; game.clock = 0;
  game.start(); game.player.deck.slots = [];
  const p = game.player; p.x = 0; p.y = 0; p.hp = 20;
  const friend = new Ally('archer', 20, 0); friend.hp = 10;
  const hostile = new Enemy('grunt', 20, 0, 1); hostile.hp = 5;
  game.allies = [friend]; game.enemies = [hostile];
  assert.equal(PLACED_TYPES.healingShrine, undefined);
  assert.equal(PLACED_TYPES.protectionTotem, undefined);
  assert.equal(game.updateSupportEncounters, undefined);
  game.objects = [];
  const field = game.addZone('healingField', { x: 0, y: 0 });
  assert.equal(field.slot.cards.some(cardId => cardBaseId(cardId) === 'heal'), true);
  field.slot.update(0.01, game);
  assert.equal(p.hp, 20 + p.stats.maxHp * 0.1);
  assert.equal(friend.hp, 15);
  assert.equal(hostile.hp, 5, 'field never heals opposing teams');
  const hp = p.hp; field.slot.update(0.1, game); assert.equal(p.hp, hp);
  p.x = field.r + 1; field.slot.update(3, game); assert.equal(p.hp, hp);
  p.x = 0; field.r = 10;
  const friendHp = friend.hp; field.slot.update(3, game); assert.equal(friend.hp, friendHp);
  const shield = game.addZone('shieldField', { x: 0, y: 0 });
  assert.ok(shield); shield.slot.update(0.01, game); assert.ok(friend.cardShield > 0);
  const medic = new Ally('medic', 0, 0);
  assert.equal(medic.life, 24); assert.ok(medic.slot.cards.some(cardId => cardBaseId(cardId) === 'heal'));
  friend.hp = 10; medic.update(0.01, game); assert.equal(friend.hp, 15);
  const shaman = new Enemy('shaman', 20, 0, 1);
  game.enemies.push(shaman); shaman.update(0.01, p, game);
  assert.ok(hostile.hp > 5, 'native shaman heals its own team');
  const lord = new Enemy('bannerlord', 0, 0, 1);
  const shooter = new Enemy('hexer', 20, 0, 1);
  game.enemies = [lord, shooter]; lord.update(0.01, p, game);
  assert.ok(shooter.cardBuffs.rage > 0 && shooter.cardBuffs.focus > 0);
  game.rebuildHash(); shooter.update(0.01, p, game);
  const bolt = game.hazards.find(s => s.kind === 'curseBolt');
  assert.ok(bolt, 'native hexer fires a new projectile type through bolt');
  bolt.x = p.x; bolt.y = p.y;
  for (const slot of bolt.slots.filter(s => s.cards.includes('entityOtherTeam'))) slot.update(0.01, game, { deferTick: true });
  assert.ok(p.directStates.mark > 0 && p.directStates.root > 0);
  assert.ok(!shooter.directStates?.root, 'hostile bolt excludes hostile allies');
  const ember = new Enemy('emberling', 0, 0, 1);
  ember.dead = true; ember.slot.onDeath(game); ember.slot.onDeath(game);
  const flame = game.zones.find(z => z.kind === 'burningField');
  assert.ok(flame); assert.equal(flame.team, 'hostile');
  assert.equal(game.zones.filter(z => z.kind === 'burningField').length, 1);
  flame.slot.update(0.01, game); assert.ok(p.directStates.burn > 0);
  const gem = new Pickup('vitalGem', 50, 0);
  game.pickups = [gem]; p.hp = 20; gem.update(0.01, game);
  assert.equal(p.hp, 20 + p.stats.maxHp * 0.1, 'new item has native healing slots');
  p.x = gem.x; p.y = gem.y; gem.update(0.01, game); assert.equal(gem.dead, true);
  for (const type of ['shaman', 'hexer', 'bannerlord', 'emberling']) {
    assert.ok(STAGES.some(s => s.pool.some(entry => entry[0] === type)), type + ' appears in stage spawns');
  }
  UI.game = game; UI.editorPage = 3; UI.showEntityEditor(game);
  assert.ok(!UI.html.includes('회복 성소') && !UI.html.includes('수호 토템'));
  UI.showCodex();
  assert.ok(!UI.html.includes('회복 성소') && !UI.html.includes('수호 토템'));
  assert.ok(!UI.html.includes('data-act="entity-gimmick"'), 'no recipe buttons');
  for (const recipe of Object.values(ENTITY_GIMMICKS)) for (const id of recipe.cards) assert.ok(CARDS[id]);
  game.start(); game.player.deck.slots = []; game.player.invuln = 10000;
  game.updateSpawns = game.updateBarrels = () => {};
  for (let i = 0; i < 1000; i++) game.step(0.05);
  assert.ok(!game.objects.some(o => ['healingShrine', 'protectionTotem'].includes(o.kind)), 'removed support structures never spawn in combat');
`, context);
console.log('New entities: native slots, fields, teams, range, cadence, enemy waves, projectiles, death fields, pickups, removed support structures and button removal passed.');
