  const meteor = game.addZone('meteor', { x: 100, y: 100 });
  const slime = game.addZone('slime', { x: 100, y: 100 });
  const slimeBlast = entityConfiguredCard(slime.slot.cards.find(id => cardBaseId(id) === 'explode'), { elem: 'fire' });
